/**
 * Every unit in the game. All stats are tunable here and nowhere else.
 * `id` values are stable keys referenced by card data and the Doom deck.
 */

const guardianGod = (element: Element, name: string, initials: string): UnitDef => ({
  id: `god-${element}`,
  name,
  initials,
  faction: 'guardian',
  element,
  cost: 0,
  ...GOD_STATS.guardian,
  isGod: true,
  abilities: [],
  text: 'Guardian god. May attack an adjacent enemy.',
});

